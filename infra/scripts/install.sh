#!/usr/bin/env bash
# DockCast one-shot installer for a fresh Ubuntu 24.04 host with >= 8 GB RAM (docs/infra.md §15).
#
#   sudo DOMAIN=dockcast.example.com CLOUDFLARE_API_TOKEN=... VAPID_SUBJECT=mailto:you@example.com \
#     bash -c "$(curl -fsSL https://raw.githubusercontent.com/asharahmed/dockcast/main/infra/scripts/install.sh)"
#
# or paste infra/cloud-init.yaml as the server's user data and never log in.
#
# Installs Docker if missing, clones the repo to /opt/dockcast, writes infra/.env with generated
# secrets, pulls the published images, starts the stack, and runs the trip-history bootstrap in
# the background. Re-running is safe: an existing .env is kept and the checkout is fast-forwarded.
#
# Inputs (env): DOMAIN (required), CLOUDFLARE_API_TOKEN (required: the Caddyfile issues
# certificates through Cloudflare DNS-01), VAPID_SUBJECT, CITY (default toronto), GHCR_OWNER
# (default asharahmed), REPO_URL, BRANCH, DEST (default /opt/dockcast),
# TRAIN_MEM_LIMIT/STEP/MAX (defaults 4g/1g/6g, sized for an 8 GB host).
set -euo pipefail

: "${DOMAIN:?set DOMAIN, e.g. dockcast.example.com}"
: "${CLOUDFLARE_API_TOKEN:?set CLOUDFLARE_API_TOKEN (Cloudflare zone DNS edit token)}"
VAPID_SUBJECT="${VAPID_SUBJECT:-mailto:admin@$DOMAIN}"
CITY="${CITY:-toronto}"
GHCR_OWNER="${GHCR_OWNER:-asharahmed}"
REPO_URL="${REPO_URL:-https://github.com/asharahmed/dockcast.git}"
BRANCH="${BRANCH:-main}"
DEST="${DEST:-/opt/dockcast}"
DRY_RUN="${DRY_RUN:-0}"            # 1: print the docker/compose steps instead of running them

log() { printf '\n[dockcast-install] %s\n' "$*"; }
run() { if [ "$DRY_RUN" = 1 ]; then printf '+ %s\n' "$*"; else "$@"; fi; }

if [ "$DRY_RUN" != 1 ] && [ "$(id -u)" -ne 0 ]; then echo "run as root (sudo)" >&2; exit 1; fi

log "1/6 Docker"
if ! command -v docker >/dev/null 2>&1; then run bash -c 'curl -fsSL https://get.docker.com | sh'; fi
if [ "$DRY_RUN" != 1 ]; then docker compose version >/dev/null 2>&1 || { echo "docker compose v2 is required" >&2; exit 1; }; fi

log "2/6 Repository -> $DEST"
if [ -d "$DEST/.git" ]; then
  git -C "$DEST" pull --ff-only
else
  git clone --depth 1 --branch "$BRANCH" "$REPO_URL" "$DEST"
fi

log "3/6 Environment file"
ENV_FILE="$DEST/infra/.env"
if [ -f "$ENV_FILE" ]; then
  log "keeping existing $ENV_FILE"
else
  PG_PASSWORD=$(openssl rand -hex 24)
  SESSION_SECRET=$(openssl rand -base64 48 | tr -d '\n')
  VAPID_JSON=$(docker run --rm node:22-alpine npx -y web-push generate-vapid-keys --json)
  VAPID_PUBLIC_KEY=$(printf '%s' "$VAPID_JSON" | sed -n 's/.*"publicKey": *"\([^"]*\)".*/\1/p')
  VAPID_PRIVATE_KEY=$(printf '%s' "$VAPID_JSON" | sed -n 's/.*"privateKey": *"\([^"]*\)".*/\1/p')
  [ -n "$VAPID_PUBLIC_KEY" ] && [ -n "$VAPID_PRIVATE_KEY" ] || { echo "could not generate VAPID keys: $VAPID_JSON" >&2; exit 1; }
  SOCK_GID=$(stat -c %g /var/run/docker.sock 2>/dev/null || echo 0)
  umask 077
  cat > "$ENV_FILE" <<ENV
# Generated by infra/scripts/install.sh on $(date -u +%FT%TZ). Every key is explained in ../.env.example.
POSTGRES_PASSWORD=$PG_PASSWORD
DATABASE_URL=postgres://postgres:$PG_PASSWORD@db:5432/dockcast
DOMAIN=$DOMAIN
PUBLIC_BASE_URL=https://$DOMAIN
SESSION_SECRET=$SESSION_SECRET
VAPID_PUBLIC_KEY=$VAPID_PUBLIC_KEY
VAPID_PRIVATE_KEY=$VAPID_PRIVATE_KEY
VAPID_SUBJECT=$VAPID_SUBJECT
CLOUDFLARE_API_TOKEN=$CLOUDFLARE_API_TOKEN
GHCR_OWNER=$GHCR_OWNER
IMAGE_TAG=latest
NODE_ENV=production
TRUST_PROXY=1
LOG_LEVEL=info
TZ=UTC
TRIPS_CACHE_DIR=/data/cache
PREDICT_INTERVAL_SEC=300
DOCKER_SOCK_GID=$SOCK_GID
TRAIN_MEM_LIMIT=${TRAIN_MEM_LIMIT:-4g}
TRAIN_MEM_STEP=${TRAIN_MEM_STEP:-1g}
TRAIN_MEM_MAX=${TRAIN_MEM_MAX:-6g}
ENV
  log "wrote $ENV_FILE"
fi

log "4/6 Pull images and start the stack"
cd "$DEST/infra"
run docker compose pull
run docker compose up -d --remove-orphans --wait

log "5/6 Bootstrap $CITY trip-history rates in the background (10-20 min)"
run bash -c "nohup docker compose run --rm -T worker-train python -m dockcast_ml bootstrap --city $CITY > '$DEST/bootstrap.log' 2>&1 &"

log "6/6 Done"
cat <<SUMMARY
  Site       https://$DOMAIN   (A record -> this host, DNS-only; Caddy gets its certificate via Cloudflare DNS-01)
  Health     curl -s https://$DOMAIN/api/v1/health
  Bootstrap  tail -f $DEST/bootstrap.log   (forecasts start on the next 5-minute tick after it finishes)
  Logs       cd $DEST/infra && docker compose logs -f
  Update     $DEST/infra/scripts/deploy.sh   (git pull, pull images, restart) or set the VPS_* GitHub secrets for push-to-deploy
SUMMARY
